#!/usr/bin/env python3
"""Refresh the CORE conference rankings used to order the Research page.

Downloads the current CORE (ICORE) list and writes data/rankings/core.yaml,
keyed by acronym (lower case). Run from the website folder:

    python3 scripts/update-rankings.py            # current list (ICORE2026)
    python3 scripts/update-rankings.py ICORE2027  # a newer list, once published

Journal quartiles come from Scimago, which blocks automated downloads,
so add those by hand in data/rankings/journals.yaml.
"""
import csv, io, sys, urllib.request, pathlib

source = sys.argv[1] if len(sys.argv) > 1 else "ICORE2026"
root = pathlib.Path(__file__).resolve().parent.parent
url = f"https://portal.core.edu.au/conf-ranks/?search=&by=all&source={source}&sort=atitle&page=1&do=Export"
raw = urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})).read().decode("utf-8", "replace")
(root / "rankings" / f"core-{source.lower()}.csv").write_text(raw)

lines = [f"# CORE conference rankings ({source}), from portal.core.edu.au.",
         "# Generated by scripts/update-rankings.py; do not edit by hand.",
         f"source: {source}", "conferences:"]
seen = set()
for row in csv.reader(io.StringIO(raw)):
    if len(row) < 5:
        continue
    acr, title, rank = row[2].strip(), row[1].strip(), row[4].strip()
    key = acr.lower()
    if not acr or key in seen:
        continue
    seen.add(key)
    esc = lambda s: s.replace('"', '\\"')
    lines.append(f'  "{esc(key)}": {{ acronym: "{esc(acr)}", title: "{esc(title)}", rank: "{esc(rank)}" }}')
(root / "data" / "rankings" / "core.yaml").write_text("\n".join(lines) + "\n")
print(f"{len(seen)} conferences written to data/rankings/core.yaml")
